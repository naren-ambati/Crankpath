/**
 * @typedef {null | boolean | number | string | YamlValue[] | { [key: string]: YamlValue }} YamlValue
 * @typedef {{ path: string, documents: readonly YamlValue[] }} FileDocs
 * @typedef {{ kind: string, reason: string | null, detail: string | null, file: string }} SourceResult
 * @typedef {{ total: number, opaque: number, byReason: Record<string, number>, atLeast: boolean, generatorsCountedOnce: number, sources: SourceResult[] }} EstateCount
 * @typedef {{ reason: string, detail: string }} Found
 */

/** @param {unknown} v @returns {v is Record<string, any>} */
function isObj(v) {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/** @param {unknown} v @returns {string | undefined} */
function str(v) {
  return typeof v === "string" ? v : undefined;
}

/**
 * FR2.3 normalisation: scheme and userinfo dropped for https, http, ssh and scp forms; host
 * lower-cased; default port, trailing `.git` and `/` dropped; non-default port kept; path
 * case-sensitive. Returns undefined for anything else, including a malformed percent escape.
 * @param {string} raw
 * @returns {string | undefined}
 */
export function normaliseRepoUrl(raw) {
  if (typeof raw !== "string" || raw.length === 0 || /[\s\p{Cc}]/u.test(raw)) return undefined;
  let host;
  let port = "";
  let p;
  const scheme = /^([a-z][a-z0-9+.-]*):\/\//i.exec(raw);
  if (scheme) {
    const s = (scheme[1] ?? "").toLowerCase();
    if (!["https", "http", "ssh", "git+ssh", "ssh+git"].includes(s)) return undefined;
    let url;
    try {
      url = new URL(raw);
      p = decodeURIComponent(url.pathname);
    } catch {
      return undefined;
    }
    host = url.hostname.toLowerCase();
    const defaults = { https: "443", http: "80", ssh: "22", "git+ssh": "22", "ssh+git": "22" };
    port = url.port !== "" && url.port !== defaults[/** @type {keyof typeof defaults} */ (s)] ? url.port : "";
  } else {
    const scp = /^(?:[^@/]+@)?([^@/:[\]]+):(?!\/\/)(.+)$/.exec(raw);
    if (!scp) return undefined;
    host = (scp[1] ?? "").toLowerCase();
    try {
      p = `/${decodeURIComponent(scp[2] ?? "")}`;
    } catch {
      return undefined;
    }
  }
  p = p
    .replace(/\/+$/, "")
    .replace(/\.git$/, "")
    .replace(/\/+$/, "");
  if (host === "" || p === "" || p === "/") return undefined;
  return `${host}${port === "" ? "" : `:${port}`}${p.startsWith("/") ? p : `/${p}`}`;
}

/** @param {string} a @param {string} own */
export function isOwnRepo(a, own) {
  const na = normaliseRepoUrl(a);
  return na !== undefined && na === normaliseRepoUrl(own);
}

/**
 * A `/`-separated path relative to the repository root, `..` resolved; undefined when it leaves
 * the root or is absolute.
 * @param {string} base a directory relative to the root ("" is the root)
 * @param {string} rel
 */
export function joinInside(base, rel) {
  if (rel.startsWith("/")) return undefined;
  /** @type {string[]} */
  const out = base === "" ? [] : base.split("/");
  for (const part of rel.split("/")) {
    if (part === "" || part === ".") continue;
    if (part === "..") {
      if (out.length === 0) return undefined;
      out.pop();
    } else out.push(part);
  }
  return out.join("/");
}

/** @param {string} filePath */
function dirOf(filePath) {
  const i = filePath.lastIndexOf("/");
  return i < 0 ? "" : filePath.slice(0, i);
}

/** @param {string} dir @param {string} file */
function isUnder(dir, file) {
  return dir === "" || file === dir || file.startsWith(`${dir}/`);
}

const KUSTOMIZATION_FILE = /(^|\/)(kustomization\.ya?ml|Kustomization)$/;

/** @param {YamlValue} doc */
function hasSops(doc) {
  return isObj(doc) && Object.hasOwn(doc, "sops");
}

/**
 * Objects of the estate. A `List` (or any `...List` kind) is expanded into its items, so an
 * Application inside one is counted.
 * @param {readonly FileDocs[]} files
 */
function objectsOf(files) {
  /** @type {{ doc: Record<string, any>, file: string }[]} */
  const objects = [];
  for (const f of files) {
    /** @type {unknown[]} */
    const stack = [...f.documents].reverse();
    while (stack.length > 0) {
      const d = stack.pop();
      if (!isObj(d)) continue;
      objects.push({ doc: d, file: f.path });
      if (typeof d.kind === "string" && d.kind.endsWith("List") && Array.isArray(d.items)) {
        for (let i = d.items.length - 1; i >= 0; i--) stack.push(d.items[i]);
      }
    }
  }
  return objects;
}

/**
 * The estate's objects and files, indexed once.
 * @param {readonly FileDocs[]} files
 * @param {readonly string[]} [unreadable] paths of YAML files BoundedReader refused
 */
export function buildIndex(files, unreadable = []) {
  const objects = objectsOf(files);
  const apiGroup = (/** @type {Record<string, any>} */ d) => String(str(d.apiVersion) ?? "").split("/")[0];
  /** @type {Map<string, FileDocs>} */
  const byPath = new Map(files.map((f) => [f.path, f]));
  const unreadableSet = new Set(unreadable);
  /** @type {Map<string, Record<string, any>>} kustomization documents by directory */
  const kustomizationByDir = new Map();
  for (const f of files) {
    if (!KUSTOMIZATION_FILE.test(f.path)) continue;
    const d = f.documents.find(isObj);
    if (isObj(d)) kustomizationByDir.set(dirOf(f.path), d);
  }
  const unreadableKustomizationDirs = new Set([...unreadableSet].filter((p) => KUSTOMIZATION_FILE.test(p)).map(dirOf));
  const configMapGenerators = new Set();
  const secretGenerators = new Set();
  for (const k of kustomizationByDir.values()) {
    for (const g of Array.isArray(k.configMapGenerator) ? k.configMapGenerator : []) {
      if (isObj(g) && str(g.name)) configMapGenerators.add(g.name);
    }
    for (const g of Array.isArray(k.secretGenerator) ? k.secretGenerator : []) {
      if (isObj(g) && str(g.name)) secretGenerators.add(g.name);
    }
  }
  /** @type {{ type: string, url: string, file: string }[]} */
  const repoCreds = [];
  let credentialWithUnknownUrl = false;
  for (const { doc, file } of objects) {
    const labels = isObj(doc.metadata) && isObj(doc.metadata.labels) ? doc.metadata.labels : {};
    if (doc.kind === "Secret") {
      const type = str(labels["argocd.argoproj.io/secret-type"]);
      if (type === "repository" || type === "repo-creds") {
        let url = hasSops(doc) ? undefined : isObj(doc.stringData) ? str(doc.stringData.url) : undefined;
        if (url === undefined && !hasSops(doc) && isObj(doc.data) && str(doc.data.url)) {
          url = Buffer.from(String(doc.data.url), "base64").toString("utf8");
        }
        if (url !== undefined && !url.startsWith("ENC[")) repoCreds.push({ type, url, file });
        else credentialWithUnknownUrl = true;
      }
    }
    if (doc.kind === "ExternalSecret" && isObj(doc.spec) && isObj(doc.spec.target) && isObj(doc.spec.target.template)) {
      const t = doc.spec.target.template;
      const tl = isObj(t.metadata) && isObj(t.metadata.labels) ? t.metadata.labels : {};
      const type = str(tl["argocd.argoproj.io/secret-type"]);
      if (type === "repository" || type === "repo-creds") {
        const url = isObj(t.data) ? str(t.data.url) : undefined;
        if (url !== undefined && !url.includes("{{")) repoCreds.push({ type, url, file });
        else credentialWithUnknownUrl = true;
      }
    }
  }
  return {
    files,
    objects,
    apiGroup,
    byPath,
    unreadableSet,
    kustomizationByDir,
    unreadableKustomizationDirs,
    configMapGenerators,
    secretGenerators,
    repoCreds,
    credentialWithUnknownUrl,
    /** files whose objects a kustomization may patch (set by classifyEstate) */
    patchedFiles: /** @type {Set<string>} */ (new Set()),
  };
}

/** @typedef {ReturnType<typeof buildIndex>} EstateIndex */

/** @param {Record<string, any>} doc */
function nsOf(doc) {
  return isObj(doc.metadata) ? str(doc.metadata.namespace) : undefined;
}

/** @param {Record<string, any>} doc */
function nameOf(doc) {
  return isObj(doc.metadata) ? str(doc.metadata.name) : undefined;
}

/**
 * Objects of `kind` named `name`; when both namespaces are known they must agree. Every match is
 * returned: a caller classifies against all of them and keeps the strongest reason.
 * @param {EstateIndex} index @param {string} kind @param {string} name @param {string | undefined} ns
 */
function findObjects(index, kind, name, ns) {
  return index.objects.filter(
    (o) =>
      o.doc.kind === kind &&
      nameOf(o.doc) === name &&
      (ns === undefined || nsOf(o.doc) === undefined || nsOf(o.doc) === ns),
  );
}

/** @param {string} host */
function badHost(host) {
  const h = host.toLowerCase().replace(/^\[|\]$/g, "");
  if (h === "localhost" || h.endsWith(".localhost")) return true;
  if (/^\d+\.\d+\.\d+\.\d+$/.test(h)) return true; // any IPv4 literal (loopback and link-local included)
  if (h.includes(":")) return true; // IPv6 literal
  return false;
}

/**
 * A chart repository URL crankpath would fetch: https:// or oci://, not an IP literal or loopback.
 * @param {string} url
 */
function chartUrlRefused(url) {
  const m = /^(https|oci):\/\/([^/?#]+)/i.exec(url);
  if (!m) return true;
  const authority = (m[2] ?? "").replace(/^[^@]*@/, "");
  const host = authority.startsWith("[")
    ? authority.slice(0, authority.indexOf("]") + 1)
    : (authority.split(":")[0] ?? "");
  return badHost(host);
}

/** @param {string} url */
function hasUserinfo(url) {
  const m = /^[a-z][a-z0-9+.-]*:\/\/([^/?#]*)/i.exec(url);
  return m !== null && (m[1] ?? "").includes("@");
}

/** @param {string} chartUrl @param {EstateIndex} index */
function needsCredentials(chartUrl, index) {
  const n = chartUrl.replace(/\/+$/, "");
  return index.repoCreds.some((c) => {
    const u = c.url.replace(/\/+$/, "");
    return c.type === "repository" ? u === n : n === u || n.startsWith(`${u}/`);
  });
}

/**
 * The strongest reason among those found, in REASON_ORDER.
 * @param {Found[]} found
 * @returns {{ reason: string | null, detail: string | null }}
 */
export function pickReason(found) {
  let best = null;
  for (const f of found) {
    if (best === null || REASON_ORDER.indexOf(f.reason) < REASON_ORDER.indexOf(best.reason)) best = f;
  }
  return best === null ? { reason: null, detail: null } : best;
}

const LIST_REF = /\{\{\s*\.?([A-Za-z0-9_.-]+)\s*\}\}/g;

/**
 * Substitutes simple `{{key}}`, `{{.key}}`, `{{ .key }}` references from a list element.
 * @param {YamlValue} value @param {Record<string, any>} element @returns {YamlValue}
 */
export function substitute(value, element) {
  if (typeof value === "string") {
    return value.replace(LIST_REF, (whole, key) => {
      let cur = /** @type {any} */ (element);
      for (const part of String(key).split(".")) {
        if (!isObj(cur) || !Object.hasOwn(cur, part)) return whole;
        cur = cur[part];
      }
      return typeof cur === "string" || typeof cur === "number" || typeof cur === "boolean" ? String(cur) : whole;
    });
  }
  if (Array.isArray(value)) return value.map((v) => substitute(v, element));
  if (isObj(value)) {
    /** @type {Record<string, YamlValue>} */
    const out = {};
    for (const [k, v] of Object.entries(value))
      Object.defineProperty(out, k, { value: substitute(v, element), enumerable: true });
    return out;
  }
  return value;
}

/** @param {unknown} v */
function templated(v) {
  return typeof v === "string" && v.includes("{{");
}

/** git generator parameters, which come from the estate's own repository */
const GIT_PARAM = /^\{\{\s*\.?path(\.[A-Za-z0-9_]+|\[\d+\])*\s*\}\}$/;

/**
 * @param {unknown} v the field value
 * @param {"none" | "git-directories" | "git-files"} params which generator parameters count as resolved
 */
function unresolved(v, params) {
  if (!templated(v)) return false;
  if (params === "none") return true;
  const s = /** @type {string} */ (v);
  const constructs = s.match(/\{\{[^}]*\}\}/g) ?? [];
  if (s.replace(/\{\{[^}]*\}\}/g, "").includes("{{")) return true; // a construct we cannot even delimit
  if (params === "git-files") return false; // any key of a files generator comes from the estate's own files
  return constructs.some((c) => !GIT_PARAM.test(c));
}

const PATCH_FIELDS = ["patches", "patchesStrategicMerge", "patchesJson6902", "replacements"];
// Every kind the classifier reads to decide about a source: a patch that may change one of them
// may change the answer.
const CONSULTED_KINDS = new Set([
  "Application",
  "ApplicationSet",
  "HelmRelease",
  "Kustomization",
  "HelmRepository",
  "GitRepository",
  "OCIRepository",
  "HelmChart",
  "Bucket",
  "Secret",
  "ConfigMap",
  "ExternalSecret",
]);

/**
 * Everything a kustomization directory reaches through its local `resources`, `bases` and
 * `components`, followed to any depth inside the repository (a visited set bounds it), with the
 * reasons the walk found on the way.
 * @param {string} start a directory relative to the root
 * @param {EstateIndex} index
 * @param {(p: string) => boolean} pathExists
 * @returns {{ dirs: Set<string>, files: Set<string>, found: Found[], patchesSources: boolean }}
 */
export function kustomizeClosure(start, index, pathExists) {
  const memo = closureMemo(index);
  const cached = memo.get(start);
  if (cached !== undefined) return cached;
  /** @type {Set<string>} */
  const dirs = new Set();
  /** @type {Set<string>} */
  const files = new Set();
  /** @type {Found[]} */
  const found = [];
  let patchesSources = false;
  // depth-first, with the directories on the current path: an entry back to one of them is a
  // kustomization cycle, which kustomize refuses, so the render would fail
  /** @type {{ dir: string, children: string[], next: number }[]} */
  const stack = [];
  /** @type {Set<string>} */
  const onPath = new Set();
  /** @param {string} dir */
  const enter = (dir) => {
    dirs.add(dir);
    onPath.add(dir);
    /** @type {string[]} */
    const children = [];
    stack.push({ dir, children, next: 0 });
    if (index.unreadableKustomizationDirs.has(dir)) {
      found.push({ reason: "unreadable-file", detail: "kustomization not readable" });
      return;
    }
    const k = index.kustomizationByDir.get(dir);
    if (k === undefined) return;
    const entries = [k.resources, k.bases, k.components].flatMap((x) => (Array.isArray(x) ? x : []));
    for (const e of entries) {
      if (typeof e !== "string") {
        found.push({ reason: "unsupported-field", detail: "kustomization entry" });
        continue;
      }
      if (e.includes("://") || e.startsWith("github.com/") || e.includes("?ref=") || e.startsWith("git@")) {
        found.push({ reason: "remote-base", detail: "kustomization" });
        continue;
      }
      const target = joinInside(dir, e);
      if (target === undefined) {
        found.push({ reason: "unreadable-file", detail: "kustomization entry outside the repository" });
        continue;
      }
      if (index.byPath.has(target) || index.unreadableSet.has(target)) files.add(target);
      else if (pathExists(target)) children.push(target);
      else found.push({ reason: "unreadable-file", detail: "kustomization entry not found" });
    }
    const plugins = [k.generators, k.transformers, k.validators].flatMap((x) => (Array.isArray(x) ? x : []));
    if (plugins.length > 0) found.push({ reason: "unsupported-field", detail: "kustomize plugin" });
    if (k.helmCharts !== undefined) found.push({ reason: "unsupported-field", detail: "kustomize helmCharts" });
    for (const field of PATCH_FIELDS) {
      for (const patch of Array.isArray(k[field]) ? k[field] : []) {
        if (patchTargetsConsulted(patch, dir, index)) patchesSources = true;
      }
    }
  };
  enter(start);
  while (stack.length > 0) {
    const top = /** @type {{ dir: string, children: string[], next: number }} */ (stack[stack.length - 1]);
    if (top.next >= top.children.length) {
      stack.pop();
      onPath.delete(top.dir);
      continue;
    }
    const child = /** @type {string} */ (top.children[top.next]);
    top.next += 1;
    if (onPath.has(child)) found.push({ reason: "unreadable-file", detail: "kustomization cycle" });
    else if (!dirs.has(child)) enter(child);
  }
  const result = { dirs, files, found, patchesSources };
  memo.set(start, result);
  return result;
}

/** @type {WeakMap<object, Map<string, { dirs: Set<string>, files: Set<string>, found: Found[], patchesSources: boolean }>>} */
const CLOSURES = new WeakMap();

/** @param {EstateIndex} index */
function closureMemo(index) {
  let m = CLOSURES.get(index);
  if (m === undefined) {
    m = new Map();
    CLOSURES.set(index, m);
  }
  return m;
}

/**
 * May this kustomize patch change an object the classifier consults? Unknown is yes.
 * @param {unknown} patch @param {string} dir @param {EstateIndex} index
 */
function patchTargetsConsulted(patch, dir, index) {
  /** @type {string[]} */
  const kinds = [];
  if (typeof patch === "string") {
    const file = joinInside(dir, patch);
    const docs = file === undefined ? undefined : index.byPath.get(file)?.documents;
    if (docs === undefined) return true;
    for (const d of /** @type {any[]} */ (docs)) if (isObj(d) && typeof d.kind === "string") kinds.push(d.kind);
  } else if (isObj(patch)) {
    if (isObj(patch.target) && typeof patch.target.kind === "string") kinds.push(patch.target.kind);
    else if (isObj(patch.source))
      return true; // a replacement: its targets are a list we do not resolve
    else if (typeof patch.patch === "string") {
      for (const m of patch.patch.matchAll(/kind:\s*["']?([A-Za-z0-9]+)/g)) kinds.push(m[1] ?? "");
    } else if (typeof patch.path === "string") return patchTargetsConsulted(patch.path, dir, index);
  }
  if (kinds.length === 0) return true;
  return kinds.some((k) => CONSULTED_KINDS.has(k));
}

/**
 * Reasons from the files under a source directory: a SOPS document anywhere under it, or a YAML
 * file BoundedReader could not read (its content is unknown).
 * @param {Iterable<string>} dirs @param {Iterable<string>} extraFiles @param {EstateIndex} index
 * @returns {Found[]}
 */
function contentReasons(dirs, extraFiles, index) {
  /** @type {Found[]} */
  const found = [];
  const dirList = [...dirs];
  const check = (/** @type {readonly YamlValue[] | undefined} */ docs) => {
    if (docs?.some(hasSops)) found.push({ reason: "encrypted-values", detail: "sops document" });
  };
  for (const f of index.files) if (dirList.some((d) => isUnder(d, f.path))) check(f.documents);
  for (const p of extraFiles) check(index.byPath.get(p)?.documents);
  // a chart's templates are Go templates that helm renders, not YAML: their being unreadable as
  // YAML says nothing about the source
  const chartTemplates = [...index.byPath.keys()]
    .filter((p) => /(^|\/)Chart\.yaml$/.test(p))
    .map((p) => (dirOf(p) === "" ? "templates" : `${dirOf(p)}/templates`));
  const extra = [...extraFiles];
  for (const p of index.unreadableSet) {
    if (chartTemplates.some((t) => isUnder(t, p))) continue;
    if (dirList.some((d) => isUnder(d, p)) || extra.includes(p)) {
      found.push({ reason: "unreadable-file", detail: "file in the source not readable" });
    }
  }
  return found;
}

/**
 * Classifies an Argo CD Application spec (or an ApplicationSet template spec).
 * @param {any} spec
 * @param {{ ownUrl: string, index: EstateIndex, pathExists: (p: string) => boolean, params?: "none" | "git-directories" | "git-files" }} ctx
 * @returns {{ reason: string | null, detail: string | null }}
 */
export function classifyArgoSpec(spec, ctx) {
  const params = ctx.params ?? "none";
  /** @type {Found[]} */
  const found = [];
  if (!isObj(spec)) return { reason: "unsupported-field", detail: "no spec" };
  /** @type {any[]} */
  const sources = Array.isArray(spec.sources) ? spec.sources : isObj(spec.source) ? [spec.source] : [];
  if (sources.length === 0) return { reason: "unsupported-field", detail: "no source" };
  /** @type {Map<string, any>} */
  const refs = new Map(sources.filter((s) => isObj(s) && str(s.ref)).map((s) => [s.ref, s]));
  for (const s of sources) {
    if (!isObj(s)) {
      found.push({ reason: "unsupported-field", detail: "source" });
      continue;
    }
    const helm = isObj(s.helm) ? s.helm : {};
    const valueFiles = Array.isArray(helm.valueFiles) ? helm.valueFiles : [];
    if (typeof s.repoURL === "string" && s.repoURL.includes("{{")) {
      found.push({ reason: "unsupported-template", detail: "repoURL" });
    }
    for (const [field, v] of [
      ["path", s.path],
      ["chart", s.chart],
      ["targetRevision", s.targetRevision],
      ["ref", s.ref],
      ...valueFiles.map((/** @type {unknown} */ f) => ["helm.valueFiles", f]),
    ]) {
      if (unresolved(v, params)) found.push({ reason: "unsupported-template", detail: String(field) });
    }
    if (s.plugin !== undefined) found.push({ reason: "unsupported-field", detail: "plugin" });
    if (helm.parameters !== undefined) found.push({ reason: "unsupported-field", detail: "helm.parameters" });
    if (helm.fileParameters !== undefined) found.push({ reason: "unsupported-field", detail: "helm.fileParameters" });
    if (JSON.stringify(s).includes("<path:")) found.push({ reason: "unsupported-field", detail: "plugin placeholder" });
    if (isObj(s.directory)) {
      for (const k of ["jsonnet", "include", "exclude"]) {
        if (s.directory[k] !== undefined) found.push({ reason: "unsupported-field", detail: `directory.${k}` });
      }
    }
    const repoURL = str(s.repoURL);
    if (repoURL === undefined) {
      found.push({ reason: "unsupported-field", detail: "no repoURL" });
      continue;
    }
    if (repoURL.includes("{{")) continue;
    const isChart = str(s.chart) !== undefined;
    // value files: each must be a readable file crankpath can find, or the source is opaque
    for (const f of valueFiles) {
      if (typeof f !== "string" || templated(f)) continue;
      if (f.includes("://")) {
        found.push({ reason: "unsupported-field", detail: "value file URL" });
        continue;
      }
      /** @type {string | undefined} */
      let file;
      if (f.startsWith("$")) {
        const name = f.slice(1).split("/")[0] ?? "";
        const refSource = refs.get(name);
        if (refSource === undefined) {
          found.push({ reason: "unsupported-field", detail: "$values ref" });
          continue;
        }
        if (!isOwnRepo(String(refSource.repoURL ?? ""), ctx.ownUrl)) continue; // the ref source is reported itself
        file = joinInside("", f.slice(name.length + 2));
      } else if (isChart) {
        found.push({ reason: "unreadable-file", detail: "value file inside a remote chart" });
        continue;
      } else {
        if (!isOwnRepo(repoURL, ctx.ownUrl)) continue;
        const p = str(s.path);
        if (p === undefined || templated(p)) continue;
        file = joinInside(joinInside("", p) ?? "", f);
      }
      if (file === undefined) found.push({ reason: "unreadable-file", detail: "value file outside the repository" });
      else if (ctx.index.unreadableSet.has(file))
        found.push({ reason: "unreadable-file", detail: "value file not readable" });
      else if (!ctx.index.byPath.has(file)) found.push({ reason: "unreadable-file", detail: "value file not found" });
      else if (ctx.index.byPath.get(file)?.documents.some(hasSops)) {
        found.push({ reason: "encrypted-values", detail: "sops value file" });
      }
    }
    if (isChart) {
      if (chartUrlRefused(repoURL)) found.push({ reason: "unsupported-field", detail: "chart repository" });
      else if (hasUserinfo(repoURL)) found.push({ reason: "private-chart", detail: "credential in the URL" });
      else if (needsCredentials(repoURL, ctx.index)) found.push({ reason: "private-chart", detail: "credential" });
      else if (ctx.index.credentialWithUnknownUrl) {
        found.push({ reason: "private-chart", detail: "a repository credential with an unreadable url" });
      }
      continue;
    }
    if (!isOwnRepo(repoURL, ctx.ownUrl)) {
      found.push({ reason: "unreadable-repo", detail: "another repository" });
      continue;
    }
    if (str(s.ref) !== undefined && str(s.path) === undefined) continue; // a values-only ref source
    const p = str(s.path) ?? "";
    if (templated(p)) continue;
    const dir = joinInside("", p);
    if (dir === undefined) {
      found.push({ reason: "unreadable-file", detail: "path outside the repository" });
      continue;
    }
    if (!ctx.pathExists(dir)) {
      found.push({ reason: "unreadable-file", detail: "path not in the repository" });
      continue;
    }
    const closure = kustomizeClosure(dir, ctx.index, ctx.pathExists);
    found.push(...closure.found);
    found.push(...contentReasons(closure.dirs, closure.files, ctx.index));
  }
  return pickReason(found);
}

const CLUSTER_GENERATORS = new Set(["clusters", "matrix", "merge"]);

/**
 * Counts and classifies one ApplicationSet: one source per list element, one per other generator.
 * @param {Record<string, any>} doc
 * @param {{ ownUrl: string, index: EstateIndex, pathExists: (p: string) => boolean }} ctx
 * @returns {{ sources: { reason: string | null, detail: string | null }[], countedOnce: number }}
 */
export function classifyApplicationSet(doc, ctx) {
  const spec = isObj(doc.spec) ? doc.spec : {};
  const template = isObj(spec.template) ? spec.template.spec : undefined;
  const generators = Array.isArray(spec.generators) ? spec.generators : [];
  if (generators.length === 0) {
    return { sources: [{ reason: "unsupported-field", detail: "no generators" }], countedOnce: 1 };
  }
  /** @type {{ reason: string | null, detail: string | null }[]} */
  const sources = [];
  let countedOnce = 0;
  for (const g of generators) {
    const kind = isObj(g)
      ? (Object.keys(g).find((k) => k !== "selector" && k !== "values" && k !== "template") ?? "")
      : "";
    const body = isObj(g) ? g[kind] : undefined;
    // a templatePatch or a generator's own template can repoint the source: not read statically
    const overridden =
      spec.templatePatch !== undefined ||
      (isObj(g) && g.template !== undefined) ||
      (isObj(body) && body.template !== undefined);
    if (kind === "list") {
      if (!isObj(body) || !Array.isArray(body.elements) || body.elementsYaml !== undefined) {
        sources.push({ reason: "unsupported-template", detail: "elementsYaml" });
        countedOnce += 1;
        continue;
      }
      if (isObj(g) && g.selector !== undefined) {
        sources.push({ reason: "unsupported-field", detail: "generator selector" });
        countedOnce += 1;
        continue;
      }
      for (const el of body.elements) {
        const element = isObj(el) ? el : {};
        sources.push(
          overridden
            ? { reason: "unsupported-template", detail: "templatePatch or generator template" }
            : classifyArgoSpec(substitute(template ?? null, element), { ...ctx, params: "none" }),
        );
      }
      continue;
    }
    countedOnce += 1;
    if (CLUSTER_GENERATORS.has(kind)) {
      sources.push({ reason: "cluster-inputs-missing", detail: kind });
      continue;
    }
    if (kind !== "git") {
      sources.push({ reason: "unsupported-field", detail: "generator" });
      continue;
    }
    const params = isObj(body) && Array.isArray(body.files) ? "git-files" : "git-directories";
    /** @type {Found[]} */
    const found = [];
    if (overridden) found.push({ reason: "unsupported-template", detail: "templatePatch or generator template" });
    const genUrl = isObj(body) ? str(body.repoURL) : undefined;
    if (genUrl === undefined) found.push({ reason: "unsupported-field", detail: "no repoURL" });
    else if (genUrl.includes("{{")) found.push({ reason: "unsupported-template", detail: "repoURL" });
    else if (!isOwnRepo(genUrl, ctx.ownUrl)) found.push({ reason: "unreadable-repo", detail: "another repository" });
    const t = classifyArgoSpec(template ?? null, { ...ctx, params });
    if (t.reason !== null) found.push({ reason: t.reason, detail: t.detail ?? "" });
    sources.push(pickReason(found));
  }
  return { sources, countedOnce };
}

const FLUX_SOURCE_GROUP = "source.toolkit.fluxcd.io";

/**
 * Resolves a Flux chart source reference to the reasons against reading it (empty when crankpath
 * could read it). Every definition that matches is checked; the strongest reason wins.
 * @param {any} ref @param {string | undefined} ns @param {any} chartSpec
 * @param {{ ownUrl: string, index: EstateIndex, pathExists: (p: string) => boolean }} ctx
 * @param {number} hops
 * @returns {Found[]}
 */
function fluxSourceReasons(ref, ns, chartSpec, ctx, hops) {
  if (!isObj(ref) || !str(ref.kind) || !str(ref.name))
    return [{ reason: "unreadable-repo", detail: "no chart source" }];
  if (templated(ref.name) || templated(ref.kind)) return [{ reason: "unsupported-template", detail: "sourceRef" }];
  const refNs = str(ref.namespace) ?? ns;
  if (ref.kind === "Bucket") return [{ reason: "unsupported-field", detail: "Bucket" }];
  const defs = findObjects(ctx.index, ref.kind, ref.name, refNs).filter(
    (o) => ctx.index.apiGroup(o.doc) === FLUX_SOURCE_GROUP,
  );
  if (defs.length === 0) return [{ reason: "unreadable-repo", detail: "source not defined in the repository" }];
  /** @type {Found[]} */
  const found = [];
  for (const def of defs) {
    if (ctx.index.patchedFiles.has(def.file))
      found.push({ reason: "unsupported-template", detail: "a consulted object is patched" });
    const spec = isObj(def.doc.spec) ? def.doc.spec : {};
    if (ref.kind === "HelmChart") {
      if (hops > 0) found.push({ reason: "unsupported-field", detail: "HelmChart chain" });
      else found.push(...fluxSourceReasons(spec.sourceRef, nsOf(def.doc) ?? refNs, spec, ctx, hops + 1));
      continue;
    }
    const url = str(spec.url) ?? "";
    if (ref.kind === "GitRepository") {
      if (!isOwnRepo(url, ctx.ownUrl)) found.push({ reason: "unreadable-repo", detail: "another repository" });
      else {
        const chartPath = isObj(chartSpec) ? str(chartSpec.chart) : undefined;
        const dir = chartPath === undefined ? undefined : joinInside("", chartPath);
        if (dir === undefined || !ctx.pathExists(dir)) {
          found.push({ reason: "unreadable-file", detail: "chart path not in the repository" });
        }
      }
      continue;
    }
    if (ref.kind === "HelmRepository" || ref.kind === "OCIRepository") {
      if (chartUrlRefused(url)) found.push({ reason: "unsupported-field", detail: "chart repository" });
      else if (spec.secretRef !== undefined || spec.certSecretRef !== undefined || hasUserinfo(url)) {
        found.push({ reason: "private-chart", detail: "secretRef" });
      }
      continue;
    }
    found.push({ reason: "unsupported-field", detail: "source kind" });
  }
  return found;
}

/**
 * @param {string} kind @param {string} name @param {string | undefined} ns @param {EstateIndex} index
 * @returns {Found | null}
 */
function valuesSourceReason(kind, name, ns, index) {
  const consulted = [...findObjects(index, kind, name, ns)];
  if (consulted.some((d) => index.patchedFiles.has(d.file))) {
    return { reason: "unsupported-template", detail: "a consulted object is patched" };
  }
  if (kind === "ConfigMap") {
    if (findObjects(index, "ConfigMap", name, ns).length > 0 || index.configMapGenerators.has(name)) return null;
    return { reason: "cluster-created-values", detail: "ConfigMap not defined" };
  }
  if (kind === "Secret") {
    const defs = findObjects(index, "Secret", name, ns);
    if (defs.some((d) => hasSops(d.doc))) return { reason: "encrypted-values", detail: "sops Secret" };
    if (defs.length > 0 || index.secretGenerators.has(name)) return null;
    return { reason: "cluster-created-values", detail: "Secret not defined" };
  }
  return { reason: "unsupported-field", detail: "values source kind" };
}

/** @param {Record<string, any>} k a Flux Kustomization */
function postBuildOf(k) {
  const spec = isObj(k.spec) ? k.spec : {};
  return isObj(spec.postBuild) ? spec.postBuild : undefined;
}

/**
 * Classifies a Flux HelmRelease.
 * @param {Record<string, any>} doc @param {string} file
 * @param {{ ownUrl: string, index: EstateIndex, pathExists: (p: string) => boolean }} ctx
 * @returns {{ reason: string | null, detail: string | null }}
 */
export function classifyHelmRelease(doc, file, ctx) {
  /** @type {Found[]} */
  const found = [];
  const spec = isObj(doc.spec) ? doc.spec : {};
  const ns = nsOf(doc);
  const chartSpec = isObj(spec.chart) && isObj(spec.chart.spec) ? spec.chart.spec : undefined;
  if (chartSpec !== undefined && (templated(chartSpec.chart) || templated(chartSpec.version))) {
    found.push({ reason: "unsupported-template", detail: "chart" });
  }
  const sourceRef = chartSpec !== undefined ? chartSpec.sourceRef : spec.chartRef;
  found.push(...fluxSourceReasons(sourceRef, ns, chartSpec, ctx, 0));
  for (const v of Array.isArray(spec.valuesFrom) ? spec.valuesFrom : []) {
    if (!isObj(v) || !str(v.kind) || !str(v.name)) {
      found.push({ reason: "unsupported-field", detail: "valuesFrom" });
      continue;
    }
    const r = valuesSourceReason(v.kind, v.name, ns, ctx.index);
    if (r !== null) found.push(r);
  }
  if (JSON.stringify(doc).includes("${")) {
    // Flux variables: readable only when a Flux Kustomization in the repository covers this file
    // and substitutes from sources the repository defines readably. No covering Kustomization,
    // or none with postBuild, means the values come from somewhere the files do not show.
    const fileDir = dirOf(file);
    const covering = ctx.index.objects.filter((k) => {
      if (
        k.doc.kind !== "Kustomization" ||
        !String(str(k.doc.apiVersion) ?? "").startsWith("kustomize.toolkit.fluxcd.io/")
      ) {
        return false;
      }
      const kspec = isObj(k.doc.spec) ? k.doc.spec : {};
      const kpath = joinInside("", str(kspec.path) ?? "");
      return kpath !== undefined && isUnder(kpath, fileDir);
    });
    if (covering.some((k) => ctx.index.patchedFiles.has(k.file))) {
      found.push({ reason: "unsupported-template", detail: "a consulted object is patched" });
    }
    const withPostBuild = covering.filter((k) => postBuildOf(k.doc) !== undefined);
    if (withPostBuild.length === 0) {
      found.push({
        reason: "unsupported-template",
        detail: "Flux variables with no substitution source in the repository",
      });
    }
    for (const k of withPostBuild) {
      const post = postBuildOf(k.doc) ?? {};
      for (const sf of Array.isArray(post.substituteFrom) ? post.substituteFrom : []) {
        if (!isObj(sf) || !str(sf.kind) || !str(sf.name)) {
          found.push({ reason: "unsupported-field", detail: "substituteFrom" });
          continue;
        }
        const r = valuesSourceReason(sf.kind, sf.name, nsOf(k.doc), ctx.index);
        if (r !== null) found.push({ reason: r.reason, detail: `substituteFrom ${r.detail}` });
      }
    }
  }
  return pickReason(found);
}

/**
 * Classifies every source of one estate. Never throws: a source the classifier cannot handle is
 * opaque `unsupported-field` (detail `unclassifiable`).
 * @param {{ ownUrl: string, files: readonly FileDocs[], pathExists: (p: string) => boolean, unreadable?: readonly string[] }} input
 * @returns {EstateCount}
 */
export function classifyEstate({ ownUrl, files, pathExists, unreadable = [] }) {
  const index = buildIndex(files, unreadable);
  const ctx = { ownUrl, index, pathExists };
  /** @type {SourceResult[]} */
  const sources = [];
  let generatorsCountedOnce = 0;
  // objects in a file a kustomization patches may not be what the file says
  /** @type {Set<string>} */
  const patchedDirs = new Set();
  const patchedFiles = index.patchedFiles;
  for (const dir of index.kustomizationByDir.keys()) {
    const c = kustomizeClosure(dir, index, pathExists);
    if (!c.patchesSources) continue;
    for (const d of c.dirs) patchedDirs.add(d);
    for (const f of c.files) patchedFiles.add(f);
  }
  for (const f of index.files) if (patchedDirs.has(dirOf(f.path))) patchedFiles.add(f.path);
  if (index.repoCreds.some((c) => patchedFiles.has(c.file))) index.credentialWithUnknownUrl = true;
  for (const { doc, file } of index.objects) {
    const group = index.apiGroup(doc);
    /** @type {string | undefined} */
    let kind;
    if (doc.kind === "Application" && group === "argoproj.io") kind = "Application";
    else if (doc.kind === "HelmRelease" && group === "helm.toolkit.fluxcd.io") kind = "HelmRelease";
    else if (doc.kind === "ApplicationSet" && group === "argoproj.io") kind = "ApplicationSet";
    if (kind === undefined) continue;
    /** @type {{ reason: string | null, detail: string | null }[]} */
    let results;
    try {
      if (kind === "ApplicationSet") {
        const r = classifyApplicationSet(doc, ctx);
        generatorsCountedOnce += r.countedOnce;
        results = r.sources;
      } else {
        results = [
          kind === "Application" ? classifyArgoSpec(doc.spec ?? null, ctx) : classifyHelmRelease(doc, file, ctx),
        ];
      }
    } catch {
      results = [{ reason: "unsupported-field", detail: "unclassifiable" }];
    }
    const annotations = isObj(doc.metadata) && isObj(doc.metadata.annotations) ? doc.metadata.annotations : {};
    for (const r of results) {
      /** @type {Found[]} */
      const extra = [];
      if (r.reason !== null) extra.push({ reason: r.reason, detail: r.detail ?? "" });
      if (hasSops(doc)) extra.push({ reason: "encrypted-values", detail: "sops document" });
      if (Object.keys(annotations).some((a) => a.startsWith("avp.kubernetes.io/"))) {
        extra.push({ reason: "unsupported-field", detail: "plugin annotation" });
      }
      if (patchedFiles.has(file)) extra.push({ reason: "unsupported-template", detail: "patched by a kustomization" });
      const best = pickReason(extra);
      sources.push({ kind, reason: best.reason, detail: best.detail, file });
    }
  }
  /** @type {Record<string, number>} */
  const byReason = {};
  let opaque = 0;
  for (const s of sources) {
    if (s.reason === null) continue;
    opaque += 1;
    byReason[s.reason] = (byReason[s.reason] ?? 0) + 1;
  }
  return {
    total: sources.length,
    opaque,
    byReason: sortKeys(byReason),
    atLeast: generatorsCountedOnce > 0 || unreadable.length > 0,
    generatorsCountedOnce,
    sources,
  };
}

/** @template T @param {Record<string, T>} o @returns {Record<string, T>} */
export function sortKeys(o) {
  /** @type {Record<string, T>} */
  const out = {};
  for (const k of Object.keys(o).sort()) out[k] = /** @type {T} */ (o[k]);
  return out;
}

/** opaque / total rounded to four decimals; null when there is nothing to divide. */
export function fraction(/** @type {number} */ opaque, /** @type {number} */ total) {
  return total === 0 ? null : Math.round((opaque / total) * 10000) / 10000;
}

/**
 * Where the counted sources stand against one third, said only as far as the counts establish it:
 * when sources were left uncounted (a floor), the estate's own share is not established.
 * @param {number} opaque @param {number} total @param {boolean} atLeast
 */
export function againstOneThird(opaque, total, atLeast) {
  if (total === 0) return "nothing counted";
  const over = opaque * 3 > total;
  // never "at most": failed renders and credentials kept elsewhere can only add opaque sources
  if (!atLeast) return over ? "over one third" : "not established";
  return over ? "over one third of the counted units; not established for the estate" : "not established";
}

/**
 * The C11 census JSON (counts only).
 * @param {{ url: string, sha: string, count: EstateCount, filesRead: number, unreadableFiles: Record<string, number>, chartTemplateFilesUnreadable: number, symlinks: number }[]} estates
 */
export function censusJson(estates) {
  const per = estates.map((e) => {
    const atLeast = e.count.atLeast || Object.values(e.unreadableFiles).some((n) => n > 0);
    return {
      againstOneThird: againstOneThird(e.count.opaque, e.count.total, atLeast),
      atLeast,
      byReason: e.count.byReason,
      chartTemplateFilesUnreadable: e.chartTemplateFilesUnreadable,
      filesRead: e.filesRead,
      fraction: fraction(e.count.opaque, e.count.total),
      generatorsCountedOnce: e.count.generatorsCountedOnce,
      opaque: e.count.opaque,
      sha: e.sha,
      symlinks: e.symlinks,
      total: e.count.total,
      unreadableFiles: sortKeys(e.unreadableFiles),
      url: e.url,
    };
  });
  const total = per.reduce((a, e) => a + e.total, 0);
  const opaque = per.reduce((a, e) => a + e.opaque, 0);
  const atLeast = per.some((e) => e.atLeast);
  /** @type {Record<string, number>} */
  const byReason = {};
  for (const e of per) for (const [k, v] of Object.entries(e.byReason)) byReason[k] = (byReason[k] ?? 0) + v;
  return {
    estates: per,
    label: LABEL,
    notSeen: [...NOT_SEEN],
    unit: UNIT,
    threshold: "1/3",
    total: {
      againstOneThird: againstOneThird(opaque, total, atLeast),
      atLeast,
      byReason: sortKeys(byReason),
      fraction: fraction(opaque, total),
      opaque,
      total,
    },
  };
}

/**
 * What the estate's own readable files need of the reader limits: the most documents in one
 * file, the deepest nesting and the most nodes in one document (counted iteratively, aliases
 * expanded). Used to show the derived limits against real need (docs/limits.md).
 * @param {readonly FileDocs[]} files
 */
export function measureNeed(files) {
  let maxDocuments = 0;
  let maxDepth = 0;
  let maxNodes = 0;
  for (const f of files) {
    maxDocuments = Math.max(maxDocuments, f.documents.length);
    for (const d of f.documents) {
      let nodes = 0;
      /** @type {[unknown, number][]} */
      const stack = [[d, 0]];
      while (stack.length > 0) {
        const [v, depth] = /** @type {[unknown, number]} */ (stack.pop());
        nodes += 1;
        if (typeof v === "object" && v !== null) {
          const level = depth + 1;
          if (level > maxDepth) maxDepth = level;
          for (const c of Array.isArray(v) ? v : Object.values(v)) stack.push([c, level]);
        }
      }
      maxNodes = Math.max(maxNodes, nodes);
    }
  }
  return { maxDocuments, maxDepth, maxNodes };
}
