// The day-1 census classifier (U11 CensusRunner, BR11.1 to BR11.3, BR11.18): pure functions over
// documents already read through BoundedReader. The rules are the ones written in docs/census.md
// (section 2 before the first count; section 2a after the B0 review). Every rule errs toward
// opaque: when the repository's files do not show that crankpath could read a source, it is
// opaque. Each rule has a table test that makes it fire and a test that it can fail. Dev-only:
// not part of the package. No file content leaves this module, only counts.

