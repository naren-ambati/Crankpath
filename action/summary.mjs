// The Action's job summary, annotations and outputs (U10 ActionEntry, contract C10, mockup M7;
// BR10.4, BR10.8, BR10.10, NFR4.1). Pure: it turns a DiffResult into text and writes nothing.
//
// Every string taken from the scanned repo arrives as the CLI escaped it (SafeText's JSON form:
// control and invisible characters already shown as codes, quote and backslash escaped). It is
// placed in double quotes after a fixed label, never at a line start, and passed through `safe`
// once more: any character outside printable ASCII becomes a code, an unescaped quote is escaped,
// and each destination's own specials become `\xNN` (Markdown and HTML characters in the summary,
// `%` in an annotation). Annotation messages and properties are then encoded as the runner reads
// them (`%25`, `%0D`, `%0A`, and `%3A`, `%2C` in properties). The summary's report lines sit in
// one fenced `text` block, so no repo text can become a link, an image, HTML or a heading.
//
// Words: the result is FAILED, NO_NEW_CYCLES_FOUND or NOT CHECKED. Nothing here says passed or OK;
// "pass" and "green" appear only negated ("Not a pass", "This job is not green"), as M7 words them.
// Self-contained on purpose (no import of the build); the vocabularies below are copies of the
// CLI's, kept equal by a test.

