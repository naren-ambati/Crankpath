/**
 * The longest repo string the Action prints. The CLI cuts repo text at `quotedTextChars` (381)
 * code points and each may print as a code of at most 10 characters (`\u{10ffff}`), plus its cut
 * marker (`... (cut at 381 of N characters)`, at most 64 characters for any N a string can hold):
 * 381 x 10 + 64. Longer text cannot come from the CLI; it is cut here too, never printed whole.
 */
export const SAFE_TEXT_QUOTED_CHARS = 381;
export const MAX_ESCAPED_CHARS = SAFE_TEXT_QUOTED_CHARS * 10 + 64;

/**
 * The job summary's own bound: GitHub keeps at most 1 MiB of summary per step (looked up
 * 2026-11-15, `docs/lookups.md`). Lines past it are counted, never silently dropped.
 */
export const SUMMARY_MAX_BYTES = 1024 * 1024;

/**
 * Annotations GitHub shows per step: 10 errors and 10 warnings (looked up 2026-11-15). The Action
 * writes at most this many of each; a last error counts what the summary lists beyond them.
 */
export const ANNOTATIONS_PER_KIND = 10;

/**
 * The gap items (and the declared facts) new in the head listed one per line in the summary:
 * crankpath's `explainListEntries` (21), one 24-line screen less a listing's own lines, the bound it
 * already uses for lists of one-line entries; the rest are counted (B8 review pass 2, m1).
 */
export const GAP_LIST_ENTRIES = 21;

/** Characters that start Markdown or HTML constructs; shown as `\xNN` in the summary. */
const MARKDOWN_SPECIAL = new Set(["`", "<", ">", "&", "[", "]", "!", "|", "*", "_", "~", "#"]);
const ANNOTATION_SPECIAL = new Set(["%"]);

/** @returns {string} */
function hexCode(/** @type {number} */ cp) {
  if (cp < 0x100) return `\\x${cp.toString(16).padStart(2, "0")}`;
  if (cp <= 0xffff) return `\\u${cp.toString(16).padStart(4, "0")}`;
  return `\\u{${cp.toString(16)}}`;
}

/**
 * Repo text (as the CLI escaped it) made safe for one destination: printable ASCII is kept,
 * escape pairs the CLI wrote (`\` and the next character) are kept as they are, an unescaped quote
 * or a trailing backslash is escaped, every other character becomes a code, and the destination's
 * specials become `\xNN`. Text over MAX_ESCAPED_CHARS is cut with a stated marker.
 */
export function safe(/** @type {string} */ text, /** @type {"markdown" | "annotation"} */ destination) {
  const special = destination === "markdown" ? MARKDOWN_SPECIAL : ANNOTATION_SPECIAL;
  const chars = Array.from(text);
  const total = chars.length;
  const kept = total > MAX_ESCAPED_CHARS ? chars.slice(0, MAX_ESCAPED_CHARS) : chars;
  let out = "";
  for (let i = 0; i < kept.length; i += 1) {
    const ch = /** @type {string} */ (kept[i]);
    const cp = /** @type {number} */ (ch.codePointAt(0));
    if (ch === "\\") {
      const next = kept[i + 1];
      const nextCp = next === undefined ? -1 : /** @type {number} */ (next.codePointAt(0));
      if (next !== undefined && nextCp >= 0x21 && nextCp <= 0x7e && !special.has(next)) {
        out += `\\${next}`;
        i += 1;
      } else out += "\\\\";
    } else if (ch === '"') out += '\\"';
    else if (cp < 0x20 || cp > 0x7e) out += hexCode(cp);
    else if (special.has(ch)) out += hexCode(cp);
    else out += ch;
  }
  if (total > MAX_ESCAPED_CHARS) out += `... (cut at ${MAX_ESCAPED_CHARS} of ${total} characters by the Action)`;
  return out;
}

/** `label "text"`: repo text always after a fixed label, never at a line start. */
export function quoted(
  /** @type {string} */ label,
  /** @type {string} */ text,
  /** @type {"markdown" | "annotation"} */ d,
) {
  if (!/^[A-Za-z][\x20-\x21\x23-\x5b\x5d-\x7e]*$/.test(label))
    throw new Error("summary: a fixed label is required (a bug)");
  return `${label} "${safe(text, d)}"`;
}

/** A workflow command's message, encoded as the runner decodes it (actions/toolkit escapeData). */
export function escapeData(/** @type {string} */ s) {
  return s.replace(/%/g, "%25").replace(/\r/g, "%0D").replace(/\n/g, "%0A");
}

/** A workflow command's property value (actions/toolkit escapeProperty). */
export function escapeProperty(/** @type {string} */ s) {
  return escapeData(s).replace(/:/g, "%3A").replace(/,/g, "%2C");
}

/**
 * One workflow command line. Properties are crankpath's own names; their values and the message
 * are encoded so no character can end the command or start another.
 */
export function workflowCommand(
  /** @type {"error" | "warning" | "notice"} */ kind,
  /** @type {Record<string, string>} */ properties,
  /** @type {string} */ message,
) {
  const props = Object.keys(properties)
    .sort(compareCodePoints)
    .map((k) => `${k}=${escapeProperty(/** @type {string} */ (properties[k]))}`)
    .join(",");
  return `::${kind}${props === "" ? "" : ` ${props}`}::${escapeData(message)}`;
}

/** A node id as text: a printable kind before its quoted `namespace/name`, else `object "<id>"`. */
export function nodeRef(/** @type {string} */ id, /** @type {"markdown" | "annotation"} */ d) {
  if (id.startsWith("external:")) return quoted("external", id.slice("external:".length), d);
  const parts = id.split("/");
  const kind = parts[0] ?? "";
  if ((parts.length === 2 || parts.length === 3) && PRINTABLE_KINDS.has(kind) && parts.every((p) => p !== "")) {
    return quoted(kind, parts.slice(1).join("/"), d);
  }
  return quoted("object", id, d);
}

/** An edge as `<from> <words> <to>`, declared edges marked, evidence file quoted when known. */
export function edgeLine(/** @type {ReportEdge} */ e, /** @type {"markdown" | "annotation"} */ d, withFile = true) {
  const words = EDGE_WORDS[e.kind];
  const middle = words === undefined ? quoted("edge of kind", e.kind, d) : words;
  const declared = e.source === "declared" ? "  [declared, not verified]" : "";
  const file = withFile && e.evidence.file !== "" ? `  [${quoted("file:", e.evidence.file, d)}]` : "";
  return `${nodeRef(e.from, d)} ${middle} ${nodeRef(e.to, d)}${declared}${file}`;
}

function plural(/** @type {number} */ n, /** @type {string} */ one, /** @type {string} */ many) {
  return `${n} ${n === 1 ? one : many}`;
}

/**
 * A side's run status as the Action states it: crankpath's, except that submodules the Action could
 * not read make an ANALYSED side ANALYSED WITH GAPS (B8 review m3: nothing reads as fully analysed
 * while a part of the tree was never read).
 */
export function effectiveState(/** @type {RunSummary} */ r) {
  return r.state === "ANALYSED" && r.submodules > 0 ? "ANALYSED WITH GAPS" : r.state;
}

/** `ANALYSED WITH GAPS (at least 2 opaque, 0 skipped)` (M7), with submodules not read when any. */
export function sideLine(/** @type {RunSummary} */ r) {
  const opaque = `${r.floor ? "at least " : ""}${r.opaque} opaque`;
  const subs = r.submodules > 0 ? `, ${plural(r.submodules, "submodule", "submodules")} not read` : "";
  return `${effectiveState(r)} (${opaque}, ${r.skipped} skipped${subs})`;
}

/** The gap reasons of one side, as the CLI's fixed words. */
function gapsLine(/** @type {string} */ side, /** @type {RunSummary} */ r) {
  const reasons = r.submodules > 0 ? [...r.reasons, "unreadable-submodules"] : r.reasons;
  if (reasons.length === 0) return `  ${side} gaps: none listed by crankpath`;
  const extra = [];
  if (r.unresolved > 0) extra.push(plural(r.unresolved, "unresolved item", "unresolved items"));
  if (r.unreadableFiles > 0) extra.push(plural(r.unreadableFiles, "file unreadable", "files unreadable"));
  const words = reasons.map((w) => safe(w, "markdown")).join(", ");
  return `  ${side} gaps: ${words}${extra.length > 0 ? ` (${extra.join("; ")})` : ""}`;
}

/** @param {NotCheckedReason} r */
function reasonText(r, /** @type {"markdown" | "annotation"} */ d) {
  const side = r.side === "both" ? "base and head" : r.side;
  const v = r.value ?? "";
  switch (r.code) {
    case "no-base":
      return "no base commit (this is not a pull_request event and no base-ref was given)";
    case "base-is-head":
      return "the base commit is the head commit, so there is nothing to compare";
    case "no-merge-base":
      return `${quoted("base-ref", v, d)} and the head share no history (no merge base)`;
    case "no-merge-base-shallow":
      return `${quoted("base-ref", v, d)} and the head have no merge base in this checkout (shallow clone)`;
    case "new-gaps":
      return `the head has ${plural(r.count ?? 0, "gap", "gaps")} the base did not have, so what they hide could not be compared (listed below)`;
    case "new-declared":
      return `the head relies on ${plural(r.count ?? 0, "declared fact", "declared facts")} the base did not (crankpath.yaml; documented by the PR author, not verified; listed below)`;
    case "outside-copy-path":
      return `${quoted("path", v, d)} in the ${side} commit leads outside the copy (through a symbolic link)`;
    case "outside-copy-config":
      return `${quoted("config", v, d)} in the ${side} commit leads outside the copy (through a symbolic link)`;
    case "outside-copy-alias":
      return `repo-alias line ${r.count ?? 0} in the ${side} commit leads outside the copy (through a symbolic link)`;
    case "copy-limit":
      return `the ${side} commit is over a bound of the Action's copy: ${limitWords(r.limit)}${v === "whole-tree" ? "; with path the repository's root the whole tree is copied, so set the path input to the estate's directory and only what crankpath reads counts" : ""}`;
    case "copy-io":
      return `the ${side} commit could not be written out of git (the file system refused a write: a name too long, no space left, or the like)`;
    case "runner-file-missing":
      return `the runner gave no ${safe(v, d)} file, so the result cannot be written where the runner reads it`;
    case "unsafe-tree":
      return `the ${side} commit holds a path crankpath will not write (an empty, dot or .git segment, or one that collides with a link)`;
    case "head-unreadable":
      return "the head commit of the checkout could not be read";
    case "not-a-checkout":
      return `${quoted("path", v, d)} is not inside a git checkout`;
    case "path-missing":
      return `${quoted("path", v, d)} is not in the ${side} commit`;
    case "config-missing":
      return `${quoted("config", v, d)} is not in the ${side} commit`;
    case "invalid-input":
      return `invalid input: ${v === "" ? "(empty)" : safe(v, d)}`;
    case "export-failed":
      return `the ${side} commit could not be copied out of the checkout`;
    case "tool-error":
      return `crankpath stopped with a tool or usage error on the ${side} (exit ${r.exit ?? 1})${v === "" ? "" : `; ${quoted("crankpath said:", v, d)}`}`;
    case "nothing-analysed":
      return `crankpath found nothing to analyse on the ${side} (NOTHING ANALYSED)`;
    case "timeout":
      return `${plural(r.count ?? 0, "render", "renders")} timed out on the ${side}, so its output may differ on a rerun`;
    case "report-unreadable":
      return `the ${side} report could not be read as crankpath's JSON (schema version 1)`;
    default:
      return quoted("reason", r.code, d);
  }
}

// The M7 form `base commit "abc123"`: the commit (input text) quoted right after crankpath's words.
function commitQuote(/** @type {string} */ v, /** @type {"markdown" | "annotation"} */ d) {
  return `"${safe(v, d)}"`;
}

/** A copy bound in words, with crankpath's limit name and value. */
function limitWords(/** @type {NotCheckedReason["limit"]} */ l) {
  if (l === undefined) return "a bound";
  const v = `${l.name} (${l.value.toLocaleString("en-US")} ${safe(l.unit, "markdown")})`;
  if (l.name === "fileBytes") return `a file over ${v}`;
  if (l.name === "filesPerScan") return `more entries than ${v}`;
  if (l.name === "fetchedRepoBytes") return `more bytes than ${v}`;
  if (l.name === "repoFetchWallClock") return `a copy longer than ${v}`;
  return safe(v, "markdown");
}

/** One gap item or declared fact new in the head, as a line after `new in the head:`. */
export function gapItemLine(/** @type {GapItem} */ g, /** @type {"markdown" | "annotation"} */ d) {
  switch (g.kind) {
    case "opaque":
      return `${g.node === null ? `opaque ${quoted("Kustomize root", g.kustomizeRoot ?? "", d)}` : `opaque source ${nodeRef(g.node, d)}`}  reason: ${safe(g.reason, d)}`;
    case "unreadable":
      return `${quoted("unreadable file", g.path, d)}  (${safe(g.reasonWord, d)})`;
    case "skipped":
      return `skipped object in ${quoted("file", g.file, d)}  document: ${g.document}${g.item === null ? "" : `  item: ${g.item}`}  reason: ${safe(g.reason, d)}`;
    case "unresolved":
      return `unresolved ${safe(g.why, d)}  ${quoted("subject:", g.subject, d)}  ${quoted("where:", g.where, d)}`;
    case "run-limit-edges":
      return `edges not kept over the run limit: ${g.head} (base ${g.base})`;
    case "submodule":
      return `submodule not read: ${quoted("path", g.path, d)}`;
    case "declared-edge":
      return `declared edge: ${edgeLine(g.edge, d, false)}`;
    case "match-override":
      return `match entry sends ${quoted("host", g.host, d)} to ${nodeRef(g.declared, d)}`;
    case "repo-mapping":
      return `repos: mapping ${quoted("url", g.url, d)} read from ${quoted("root", g.root, d)}`;
    default:
      return "an item of a kind this Action does not know";
  }
}

/** The capped item lines of one list, with the count of the rest. */
function itemLines(/** @type {GapItem[]} */ items, /** @type {string} */ what) {
  const lines = items.slice(0, GAP_LIST_ENTRIES).map((g) => `  new in the head: ${gapItemLine(g, "markdown")}`);
  if (items.length > GAP_LIST_ENTRIES) {
    lines.push(
      `  and ${items.length - GAP_LIST_ENTRIES} more ${what} new in the head; run crankpath on the head commit to see them all`,
    );
  }
  return lines;
}

/** @param {NotCheckedReason} r */
function reasonLine(r, /** @type {"markdown" | "annotation"} */ d) {
  if (r.code === "base-not-in-checkout-shallow")
    return `base commit ${commitQuote(r.value ?? "", d)} not in checkout (shallow clone)`;
  if (r.code === "base-not-in-checkout") return `base commit ${commitQuote(r.value ?? "", d)} not in checkout`;
  return reasonText(r, d);
}

/** @param {ReportCrank} k */
function crankLine(k, /** @type {"markdown" | "annotation"} */ d) {
  const n = /^crank:(\d+)$/.exec(k.id);
  const head = n ? `crank ${n[1]}` : quoted("crank", k.id, d);
  const ref = k.ref === null ? "" : `  ${quoted("ref:", k.ref, d)}`;
  const what = [];
  if (k.createdNodes.length > 0) what.push(`creates ${plural(k.createdNodes.length, "node", "nodes")}`);
  if (k.reroutedEdges.length > 0) what.push(`reroutes ${plural(k.reroutedEdges.length, "node", "nodes")}`);
  if (!k.matched) what.push("matched no node");
  return `${head} ${quoted("by:", k.by, d)}${ref}  (${what.join(", ")}; documented by the PR author, not verified)`;
}

/**
 * The "Not a pass:" clauses for NO_NEW_CYCLES_FOUND (M7): what the result does not cover.
 * @param {DiffResult} diff
 */
function notAPassClauses(diff) {
  const base = /** @type {RunSummary} */ (diff.base);
  const head = /** @type {RunSummary} */ (diff.head);
  const clauses = [];
  const atLeast = head.floor ? "at least " : "";
  if (head.opaque > base.opaque) {
    clauses.push(
      `the head has ${atLeast}${plural(head.opaque, "opaque source", "opaque sources")} (base ${base.floor ? "at least " : ""}${base.opaque}), so cycles inside them could not be seen`,
    );
  } else if (head.opaque > 0) {
    clauses.push(
      `the head has ${atLeast}${plural(head.opaque, "opaque source", "opaque sources")}, so cycles inside them could not be seen`,
    );
  }
  if (diff.unchangedCycles.length > 0) {
    clauses.push(
      `${plural(diff.unchangedCycles.length, "uncranked cycle the base already had is", "uncranked cycles the base already had are")} still there`,
    );
  }
  const declared = declaredCount(diff);
  if (declared > 0) {
    clauses.push(
      `it rests on ${plural(declared, "declared fact", "declared facts")} this pull request added or changed, which crankpath does not verify`,
    );
  }
  if (diff.hiddenNew.length > 0) {
    clauses.push(`${plural(diff.hiddenNew.length, "cycle is", "cycles are")} hidden by match entries and not checked`);
  }
  if (effectiveState(head) !== "ANALYSED") clauses.push("the head analysis has gaps (listed below)");
  if (clauses.length === 0) {
    clauses.push("it says only that no uncranked head cycle has an edge the base lacks or lost a crank the base had");
  }
  return clauses;
}

/** @param {DiffResult} diff */
function declaredCount(diff) {
  const c = diff.declared;
  return (
    c.cranks.length + c.declaredEdges.length + c.externals.length + c.matchOverrides.length + c.repoMappings.length
  );
}

/**
 * @typedef {{ crankpathVersion: string, baseCommit: string | null, headCommit: string | null,
 *   pathPrefix: string, baseRef?: string }} RenderContext
 */

/**
 * The report lines (inside the summary's text fence) in three parts: lines always written first,
 * the listing (cycles and declared facts, bounded by the summary size) and the closing lines,
 * always written last.
 * @param {DiffResult} diff
 */
function reportLines(diff) {
  const d = "markdown";
  /** @type {string[]} */
  const lead = [];
  /** @type {string[]} */
  const listing = [];
  /** @type {string[]} */
  const closing = [];
  if (diff.result === "NOT_CHECKED") {
    for (const r of diff.notChecked) lead.push(`NOT CHECKED: ${reasonLine(r, d)}. This job is not green.`);
    listing.push(...itemLines(diff.newGaps, "gaps"), ...itemLines(diff.newDeclared, "declared facts"));
    for (const r of diff.notChecked) {
      const over = r.over ?? [];
      for (const o of over.slice(0, GAP_LIST_ENTRIES)) {
        listing.push(
          `  over the bound: ${quoted("path", o.path, d)}  (${o.size.toLocaleString("en-US")} ${safe(o.unit, d)})`,
        );
      }
      if (over.length > GAP_LIST_ENTRIES)
        listing.push(`  and ${over.length - GAP_LIST_ENTRIES} more paths over the bound`);
    }
    if (diff.base !== null && diff.head !== null) {
      closing.push(`Base: ${sideLine(diff.base)}.  Head: ${sideLine(diff.head)}.`);
    } else if (diff.base !== null) closing.push(`Base: ${sideLine(diff.base)}.  Head: not analysed.`);
    else if (diff.head !== null) closing.push(`Base: not analysed.  Head: ${sideLine(diff.head)}.`);
    closing.push("Result: NOT CHECKED (no comparison was made; the job is not green)");
    return { lead, listing, closing };
  }

  const base = /** @type {RunSummary} */ (diff.base);
  const head = /** @type {RunSummary} */ (diff.head);
  if (diff.newCycles.length > 0) {
    const removed = diff.newCycles.filter((c) => c.why === "crank-removed").length;
    lead.push(
      `New uncranked cycles: ${diff.newCycles.length}${removed > 0 ? `  (${removed} with a crank removed by this pull request)` : ""}`,
    );
    for (const n of diff.newCycles) {
      const c = n.cycle;
      const where =
        n.why === "crank-removed"
          ? "(cranked in base, uncranked in head)"
          : n.why === "new-edges"
            ? `(head only; base has ${n.baseEdgesPresent} of its edges)`
            : "(its base component could not be found)";
      listing.push(`  cycle ${safe(c.id, d)}  label: ${safe(c.label, d)}  edges: ${c.edges.length}   ${where}`);
      if (c.label !== "extracted")
        listing.push("    it rests on a declared edge or match entry (declared, not verified)");
      for (const e of n.newEdges) listing.push(`    ${edgeLine(e, d)}`);
      for (const k of n.baseCranks)
        listing.push(
          `    cranked in base by: ${crankLine(k, d).replace("; documented by the PR author", "; documented")}`,
        );
    }
  } else {
    lead.push(`No new uncranked cycle found. Not a pass: ${notAPassClauses(diff).join("; ")}.`);
  }
  if (diff.unchangedCycles.length > 0) {
    listing.push(
      `Uncranked cycles the base already had: ${diff.unchangedCycles.length} (not new, so they do not fail this check)`,
    );
    for (const c of diff.unchangedCycles)
      listing.push(`  cycle ${safe(c.id, d)}  label: ${safe(c.label, d)}  edges: ${c.edges.length}`);
  }
  if (diff.crankedInHead.length > 0) {
    listing.push(`Cycles cranked in the head: ${diff.crankedInHead.length} (by cranks documented, not verified)`);
    for (const c of diff.crankedInHead) {
      const by = c.addedByPr ? "a crank this pull request adds" : "a crank the base already had";
      listing.push(
        `  cycle ${safe(c.cycle.id, d)}  label: cranked  edges: ${c.cycle.edges.length}   (cranked by ${by}; ${c.newEdges} of its edges are new in this pull request)`,
      );
    }
  }

  const dc = diff.declared;
  const core = dc.cranks.length + dc.declaredEdges.length + dc.externals.length;
  if (core === 0) listing.push("Cranks, declared edges and externals added by this pull request: 0");
  else {
    listing.push(
      `Cranks, declared edges and externals added or changed by this pull request: ${core} (documented by the PR author, not verified)`,
    );
    for (const k of dc.cranks) listing.push(`  ${crankLine(k, d)}`);
    for (const e of dc.declaredEdges) listing.push(`  declared edge: ${edgeLine(e, d, false)}`);
    for (const x of dc.externals) {
      const how = x.servedBy === null ? `cold start: ${safe(x.coldStart, d)}` : `served by ${nodeRef(x.servedBy, d)}`;
      listing.push(`  ${nodeRef(x.id, d)}  ${how}  (documented by the PR author, not verified)`);
    }
  }
  const more = dc.matchOverrides.length + dc.repoMappings.length;
  if (more > 0) {
    listing.push(
      `Match entries and repos: mappings added or changed by this pull request: ${more} (documented by the PR author, not verified)`,
    );
    for (const m of dc.matchOverrides)
      listing.push(
        `  match ${quoted("entry", m.keyPath, d)} sends ${quoted("host", m.host, d)} to ${nodeRef(m.declared, d)}`,
      );
    for (const m of dc.repoMappings)
      listing.push(`  repos: ${quoted("url", m.url, d)} read from ${quoted("root", m.root, d)}`);
  }
  if (diff.hiddenNew.length > 0) {
    listing.push(`Cycles hidden by match entries in the head, not in the base: ${diff.hiddenNew.length} (not checked)`);
    for (const h of diff.hiddenNew)
      listing.push(
        `  cycle ${safe(h.id, d)}  label: ${safe(h.label, d)}  nodes: ${h.nodeIds.length}  hidden by: ${h.hiddenBy.map((k) => `"${safe(k, d)}"`).join(", ")}`,
      );
  }

  if (diff.newGaps.length > 0) {
    listing.push(`Gaps new in the head: ${diff.newGaps.length} (cycles inside them could not be seen)`);
    listing.push(...itemLines(diff.newGaps, "gaps"));
  }
  closing.push(`Base: ${sideLine(base)}.  Head: ${sideLine(head)}.`);
  if (effectiveState(base) !== "ANALYSED") closing.push(gapsLine("base", base));
  if (effectiveState(head) !== "ANALYSED") closing.push(gapsLine("head", head));
  if (head.opaque > base.opaque) {
    closing.push(`  the head has more opaque sources than the base (${head.opaque} against ${base.opaque})`);
  }
  if (diff.result === "FAILED") {
    const removedOnly = diff.newCycles.every((c) => c.why === "crank-removed");
    closing.push(`Result: FAILED${removedOnly ? " (crank removed by this pull request)" : " (new uncranked cycle)"}`);
  } else closing.push("Result: NO_NEW_CYCLES_FOUND (not a pass; see the first line)");
  return { lead, listing, closing };
}

function stopLine(/** @type {number} */ n, /** @type {number} */ maxBytes) {
  return `... ${plural(n, "more line", "more lines")} not shown: the job summary holds at most ${maxBytes} bytes; run crankpath on the head commit to see every one`;
}

const encoder = new TextEncoder();
const bytes = (/** @type {string} */ s) => encoder.encode(s).length;

/**
 * The job summary as Markdown: a fixed heading, then the report lines in one `text` fence. The
 * listing is cut, with a counted stop line, so the whole summary stays within `maxBytes`.
 * @param {DiffResult} diff
 * @param {RenderContext} ctx
 */
export function renderSummary(diff, ctx, maxBytes = SUMMARY_MAX_BYTES) {
  const word = diff.result === "NOT_CHECKED" ? "NOT CHECKED" : diff.result;
  const heading = `## crankpath: ${word}${diff.result === "NO_NEW_CYCLES_FOUND" ? " (not a pass)" : ""}`;
  const commits =
    `crankpath ${safe(ctx.crankpathVersion, "markdown")}; base commit ` +
    `${ctx.baseCommit === null ? "(none)" : safe(ctx.baseCommit.slice(0, 12), "markdown")}` +
    `${ctx.baseCommit === null || ctx.baseRef === undefined ? "" : ` (the merge base of ${quoted("base-ref", ctx.baseRef, "markdown")} and the head)`}; head commit ` +
    `${ctx.headCommit === null ? "(none)" : safe(ctx.headCommit.slice(0, 12), "markdown")}` +
    `${ctx.pathPrefix === "" ? "" : `; scanned ${quoted("path", ctx.pathPrefix, "markdown")}`}.`;
  const { lead, listing, closing } = reportLines(diff);
  const open = `${heading}\n\n${commits}\n\n\`\`\`text\n`;
  const close = "```\n";
  const fixed = bytes(open) + bytes(close) + [...lead, ...closing].reduce((n, l) => n + bytes(l) + 1, 0);
  // room for the stop line: its longest form counts every listing line as not shown
  let budget = maxBytes - fixed - (bytes(stopLine(listing.length, maxBytes)) + 1);
  const kept = [];
  let i = 0;
  for (; i < listing.length; i += 1) {
    const line = /** @type {string} */ (listing[i]);
    const cost = bytes(line) + 1;
    if (cost > budget) break;
    budget -= cost;
    kept.push(line);
  }
  if (i < listing.length) kept.push(stopLine(listing.length - i, maxBytes));
  return `${open}${[...lead, ...kept, ...closing].join("\n")}\n${close}`;
}

/**
 * The workflow commands (annotations) for a result: at most ANNOTATIONS_PER_KIND errors and as
 * many warnings, every repo string quoted and the command encoded.
 * @param {DiffResult} diff
 * @param {RenderContext} ctx
 */
export function renderAnnotations(diff, ctx) {
  const d = "annotation";
  /** @type {string[]} */
  const errors = [];
  /** @type {string[]} */
  const warnings = [];
  if (diff.result === "NOT_CHECKED") {
    for (const r of diff.notChecked.slice(0, ANNOTATIONS_PER_KIND)) {
      errors.push(
        workflowCommand(
          "error",
          { title: "crankpath NOT CHECKED" },
          `NOT CHECKED: ${reasonLine(r, d)}. This job is not green.`,
        ),
      );
    }
    return [...errors];
  }
  const room = diff.newCycles.length > ANNOTATIONS_PER_KIND ? ANNOTATIONS_PER_KIND - 1 : ANNOTATIONS_PER_KIND;
  for (const n of diff.newCycles.slice(0, room)) {
    const c = n.cycle;
    /** @type {Record<string, string>} */
    const props = { title: "crankpath new uncranked cycle" };
    let message;
    if (n.why === "crank-removed") {
      message = `New uncranked cycle ${safe(c.id, d)} (label: ${safe(c.label, d)}, ${plural(c.edges.length, "edge", "edges")}): cranked in base, uncranked in head (crank removed by this pull request).`;
    } else {
      const first = n.newEdges[0];
      message = `New uncranked cycle ${safe(c.id, d)} (label: ${safe(c.label, d)}, ${plural(c.edges.length, "edge", "edges")}; head only, base has ${n.baseEdgesPresent} of its edges)${first === undefined ? "." : `: ${edgeLine(first, d)}`}`;
      const file = first === undefined ? undefined : annotationFile(first.evidence.file, ctx.pathPrefix);
      if (file !== undefined && first !== undefined) {
        props.file = file;
        if (first.evidence.line !== null) props.line = String(first.evidence.line);
      }
    }
    errors.push(workflowCommand("error", props, message));
  }
  if (diff.newCycles.length > room) {
    errors.push(
      workflowCommand(
        "error",
        { title: "crankpath new uncranked cycle" },
        `${diff.newCycles.length - room} more new uncranked cycles are listed in the job summary.`,
      ),
    );
  }
  const declared = declaredCount(diff);
  if (declared > 0) {
    warnings.push(
      workflowCommand(
        "warning",
        { title: "crankpath declared facts" },
        `This pull request adds or changes ${plural(declared, "declared fact", "declared facts")} (cranks, declared edges, externals, match entries or repos: mappings): documented by the PR author, not verified. They are listed in the job summary.`,
      ),
    );
  }
  if (diff.hiddenNew.length > 0) {
    warnings.push(
      workflowCommand(
        "warning",
        { title: "crankpath hidden cycles" },
        `${plural(diff.hiddenNew.length, "cycle is", "cycles are")} hidden by match entries in the head and not checked.`,
      ),
    );
  }
  const head = /** @type {RunSummary} */ (diff.head);
  const base = /** @type {RunSummary} */ (diff.base);
  if (effectiveState(head) !== "ANALYSED") {
    warnings.push(
      workflowCommand(
        "warning",
        { title: "crankpath gaps" },
        `The head analysis has gaps: Head: ${sideLine(head)}. Base: ${sideLine(base)}. Cycles inside what was not read could not be seen; the gaps are listed in the job summary.`,
      ),
    );
  } else if (effectiveState(base) !== "ANALYSED") {
    warnings.push(
      workflowCommand(
        "warning",
        { title: "crankpath gaps" },
        `The base analysis has gaps: Base: ${sideLine(base)}. An edge the base did not show counts as absent from it, so a head cycle may be reported new; the gaps are listed in the job summary.`,
      ),
    );
  }
  return [...errors, ...warnings.slice(0, ANNOTATIONS_PER_KIND)];
}

/**
 * The `file` property of an annotation: the evidence file under the scanned path, only when it is a
 * plain repository path (no `alias:` label, no escape code, no `..`); otherwise none.
 */
export function annotationFile(/** @type {string} */ file, /** @type {string} */ pathPrefix) {
  if (
    !/^[A-Za-z0-9._/@+-]+$/.test(file) ||
    file.startsWith("/") ||
    file.split("/").some((s) => s === ".." || s === "")
  ) {
    return undefined;
  }
  return pathPrefix === "" ? file : `${pathPrefix}/${file}`;
}

/**
 * The step outputs (C10): `result` and `new-cycles`. With NOT_CHECKED no count exists, so
 * `new-cycles` is empty, never 0.
 * @param {DiffResult} diff
 */
export function renderOutputs(diff) {
  const count = diff.result === "NOT_CHECKED" ? "" : String(diff.newCycles.length);
  return `result=${diff.result}\nnew-cycles=${count}\n`;
}

/** The step's exit status: 0 only for NO_NEW_CYCLES_FOUND (OD-11: NOT CHECKED is not green). */
export function exitStatus(/** @type {DiffResult} */ diff) {
  return diff.result === "NO_NEW_CYCLES_FOUND" ? 0 : 1;
}
